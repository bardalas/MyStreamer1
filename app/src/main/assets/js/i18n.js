// the language of the profile this page is opened in (core/store.js)
let UI = (() => { const l = store.get('settings', {})?.uiLang; return STRINGS[l] ? l : 'he'; })();
/** A UI string, falling back to Hebrew and then to the key itself. */
function tr(key, vars){
  const s = STRINGS[UI]?.[key] ?? STRINGS.he[key] ?? key;
  return vars ? s.replace(/\{(\w+)\}/g, (m, k) => k in vars ? vars[k] : m) : s;
}
/** Set lang and direction, and fill in the static markup (data-i18n, data-i18n-ph, data-i18n-aria). */
/**
 * Switch the language the page speaks.
 *
 * Every string is read through UI, so only this module may move it - an importer holds a copy of the
 * value, not the variable, and assigning to it from outside is a TypeError against a module binding.
 * That is what switching the language used to do: throw, and change nothing.
 */
function setUiLang(l){ if(!STRINGS[l] || l === UI) return; UI = l; applyUiLang(); }

function applyUiLang(){
  const r = document.documentElement;
  r.lang = UI; r.dir = dirOf(UI);
  document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = tr(el.dataset.i18n); });
  document.querySelectorAll('[data-i18n-ph]').forEach(el => { el.placeholder = tr(el.dataset.i18nPh); });
  document.querySelectorAll('[data-i18n-aria]').forEach(el => { el.setAttribute('aria-label', tr(el.dataset.i18nAria)); });
}
/** Console helper: keys one language has and another lacks. */
const missingStrings = () => { const all = new Set(Object.values(STRINGS).flatMap(Object.keys)); return Object.fromEntries(Object.keys(STRINGS).map(l => [l, [...all].filter(k => !(k in STRINGS[l]))])); };
/** The key that moves forward along a row: ArrowLeft in right-to-left, ArrowRight in left-to-right. */
const FWD = () => document.documentElement.dir === 'rtl' ? 'left' : 'right';
applyUiLang();

